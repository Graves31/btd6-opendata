# The logo's font (Luckiest Guy, Apache 2.0, from @fontsource/luckiest-guy in node_modules) for the scripts that draw
# the logo: build_icons.py (site icon + the CSS subset the header uses) and build_og.py (link preview).
import base64
import io
from pathlib import Path

from fontTools.subset import Options, Subsetter
from fontTools.ttLib import TTFont
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "node_modules/@fontsource/luckiest-guy/files/luckiest-guy-latin-400-normal.woff2"
# Every letter the logo writes ("BTD6 Open Data", in either case).
CHARS = "BTD6 OPENDATAopendata"
# Colours of the logo (docs/game-ui.md): white "BTD6", yellow "Open Data", a heavy dark-blue outline and drop.
WHITE, YELLOW, OUTLINE, DROP = "#ffffff", "#ffd60a", "#0b2a5c", "#06173a"


def font() -> TTFont:
    return TTFont(SRC)


def ttf_bytes() -> io.BytesIO:
    """The whole font as TTF bytes (Pillow's ImageFont.truetype reads it)."""
    f = font()
    f.flavor = None
    buf = io.BytesIO()
    f.save(buf)
    buf.seek(0)
    return buf


def css() -> str:
    """@font-face for the header logo: the logo's letters only, inlined (no request, no flash of fallback text)."""
    f = font()
    opts = Options()
    opts.flavor = "woff2"
    opts.layout_features = ["kern"]
    sub = Subsetter(options=opts)
    sub.populate(text=CHARS)
    sub.subset(f)
    buf = io.BytesIO()
    f.flavor = "woff2"
    f.save(buf)
    b64 = base64.b64encode(buf.getvalue()).decode()
    return (
        "/* Generated by scripts/build_icons.py: the logo's letters of Luckiest Guy (Apache 2.0), inlined. */\n"
        "@font-face {\n"
        '  font-family: "Logo";\n'
        "  font-style: normal;\n"
        "  font-weight: 400;\n"
        "  font-display: block;\n"
        f'  src: url("data:font/woff2;base64,{b64}") format("woff2");\n'
        "}\n"
    )


def word(text: str, size: int, fill: str, stroke: int) -> Image.Image:
    """One word in the logo style, as an image: a two-step drop, the outline, then the fill."""
    f = ImageFont.truetype(ttf_bytes(), size)
    box = f.getbbox(text, stroke_width=stroke)
    drop = max(1, round(size * 0.09))
    img = Image.new("RGBA", (box[2] - box[0], box[3] - box[1] + drop * 2))
    d = ImageDraw.Draw(img)
    o = (-box[0], -box[1])
    d.text((o[0], o[1] + drop * 2), text, font=f, fill=DROP, stroke_width=stroke, stroke_fill=DROP)
    d.text((o[0], o[1] + drop), text, font=f, fill=OUTLINE, stroke_width=stroke, stroke_fill=OUTLINE)
    d.text(o, text, font=f, fill=fill, stroke_width=stroke, stroke_fill=OUTLINE)
    return img
